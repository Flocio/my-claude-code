#!/usr/bin/env bash
set -euo pipefail

KIMI_MODE="${KIMI_MODE:-code}"

case "$KIMI_MODE" in
  code)
    API_KEY="${KIMI_API_KEY:-}"
    DEFAULT_BASE_URL="https://api.kimi.com/coding/"
    DEFAULT_MODEL="kimi-for-coding"
    KEY_HINT="KIMI_API_KEY"
    ;;
  platform | moonshot)
    API_KEY="${MOONSHOT_API_KEY:-${KIMI_API_KEY:-}}"
    DEFAULT_BASE_URL="https://api.moonshot.ai/anthropic"
    DEFAULT_MODEL="kimi-k2.5"
    KEY_HINT="MOONSHOT_API_KEY or KIMI_API_KEY"
    ;;
  *)
    echo "Unsupported KIMI_MODE: $KIMI_MODE. Use code or platform." >&2
    exit 2
    ;;
esac

if [[ -z "$API_KEY" ]]; then
  echo "Set $KEY_HINT first." >&2
  exit 2
fi

MODEL="${KIMI_MODEL:-$DEFAULT_MODEL}"
SMALL_MODEL="${KIMI_SMALL_FAST_MODEL:-$MODEL}"

export ANTHROPIC_BASE_URL="${KIMI_BASE_URL:-$DEFAULT_BASE_URL}"
export ANTHROPIC_API_KEY="$API_KEY"
export ANTHROPIC_AUTH_TOKEN="$API_KEY"
export ANTHROPIC_MODEL="$MODEL"
export ANTHROPIC_DEFAULT_OPUS_MODEL="${KIMI_OPUS_MODEL:-$MODEL}"
export ANTHROPIC_DEFAULT_SONNET_MODEL="${KIMI_SONNET_MODEL:-$MODEL}"
export ANTHROPIC_DEFAULT_HAIKU_MODEL="${KIMI_HAIKU_MODEL:-$SMALL_MODEL}"
export ANTHROPIC_SMALL_FAST_MODEL="$SMALL_MODEL"
export CLAUDE_CODE_SUBAGENT_MODEL="${KIMI_SUBAGENT_MODEL:-$SMALL_MODEL}"
export CLAUDE_CODE_EFFORT_LEVEL="${KIMI_EFFORT_LEVEL:-unset}"

export API_TIMEOUT_MS="${API_TIMEOUT_MS:-3000000}"
export ENABLE_TOOL_SEARCH="${ENABLE_TOOL_SEARCH:-0}"
export CLAUDE_CODE_DISABLE_EXPERIMENTAL_BETAS="${CLAUDE_CODE_DISABLE_EXPERIMENTAL_BETAS:-1}"
export CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC="${CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC:-1}"
export DISABLE_TELEMETRY="${DISABLE_TELEMETRY:-1}"

CLAUDE_BIN="${CLAUDE_BIN:-claude}"
exec "$CLAUDE_BIN" --bare --thinking "${KIMI_THINKING:-disabled}" "$@"
