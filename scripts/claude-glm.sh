#!/usr/bin/env bash
set -euo pipefail

API_KEY="${GLM_API_KEY:-${ZHIPU_API_KEY:-${BIGMODEL_API_KEY:-}}}"

if [[ -z "$API_KEY" ]]; then
  echo "Set GLM_API_KEY, ZHIPU_API_KEY, or BIGMODEL_API_KEY first." >&2
  exit 2
fi

MODEL="${GLM_MODEL:-glm-5.1}"
SONNET_MODEL="${GLM_SONNET_MODEL:-glm-5-turbo}"
HAIKU_MODEL="${GLM_HAIKU_MODEL:-glm-4.5-air}"
SMALL_MODEL="${GLM_SMALL_FAST_MODEL:-$HAIKU_MODEL}"

export ANTHROPIC_BASE_URL="${GLM_BASE_URL:-https://open.bigmodel.cn/api/anthropic}"
export ANTHROPIC_API_KEY="$API_KEY"
export ANTHROPIC_AUTH_TOKEN="$API_KEY"
export ANTHROPIC_MODEL="$MODEL"
export ANTHROPIC_DEFAULT_OPUS_MODEL="${GLM_OPUS_MODEL:-$MODEL}"
export ANTHROPIC_DEFAULT_SONNET_MODEL="$SONNET_MODEL"
export ANTHROPIC_DEFAULT_HAIKU_MODEL="$HAIKU_MODEL"
export ANTHROPIC_SMALL_FAST_MODEL="$SMALL_MODEL"
export CLAUDE_CODE_SUBAGENT_MODEL="${GLM_SUBAGENT_MODEL:-$SMALL_MODEL}"
export CLAUDE_CODE_EFFORT_LEVEL="${GLM_EFFORT_LEVEL:-unset}"

export API_TIMEOUT_MS="${API_TIMEOUT_MS:-3000000}"
export ENABLE_TOOL_SEARCH="${ENABLE_TOOL_SEARCH:-0}"
export CLAUDE_CODE_DISABLE_EXPERIMENTAL_BETAS="${CLAUDE_CODE_DISABLE_EXPERIMENTAL_BETAS:-1}"
export CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC="${CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC:-1}"
export DISABLE_TELEMETRY="${DISABLE_TELEMETRY:-1}"

CLAUDE_BIN="${CLAUDE_BIN:-claude}"
exec "$CLAUDE_BIN" --bare --thinking "${GLM_THINKING:-disabled}" "$@"
